import { z } from "zod";
import { EXPERIMENTS } from "./experiments.ts";
import {
  ANALYTICS_SCHEMA_VERSION,
  DEVICE_CLASSES,
  analyticsSource,
  EVENT_NAMES,
  DELETION_KEY_PATTERN,
  MAX_EVENTS_PER_BATCH,
  OWNER_HASH_PATTERN,
  ROUTES,
  VIEWPORT_BANDS,
  normalizeEvent,
  routeId,
  validateEventProps,
  type EventName,
} from "./analytics.ts";
import {
  acquisitionChannelSchema,
  contextSchema,
  experimentIdSchema,
  sourceSchema,
  visitorIdSchema,
} from "./schemas.ts";

/**
 * Server-side envelopes for analytics events (schema v2). Kept apart from the form schemas so
 * the browser bundle, which never validates events with zod, does not carry them.
 */

/** Random per-event and per-page-load ids generated by the browser (UUIDs in practice). */
export const analyticsIdSchema = z
  .string()
  .regex(
    /^(?:[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}|[a-z0-9]{8}-[a-z0-9]{10})$/i,
  );
const eventPropValue = z.union([z.string().max(120), z.number(), z.boolean()]);
const eventProps = z.record(z.string().max(40), eventPropValue);

/** One v2 event exactly as the browser sends it. Unknown keys anywhere are rejected. */
export const createEventSchema = z
  .strictObject({
    v: z.literal(ANALYTICS_SCHEMA_VERSION),
    event_id: analyticsIdSchema,
    view_id: analyticsIdSchema,
    name: z.enum(EVENT_NAMES as [EventName, ...EventName[]]),
    experiment_id: experimentIdSchema.refine((id) => EXPERIMENTS.some((e) => e.id === id)),
    source: sourceSchema.default("direct").transform(analyticsSource),
    acquisition_channel: acquisitionChannelSchema.default("direct"),
    visitor_id: visitorIdSchema,
    /** SHA-256 of this browser's deletion key; lets only that browser erase these events. */
    owner: z.string().regex(OWNER_HASH_PATTERN).optional(),
    route: z.enum(ROUTES),
    device: z.enum(DEVICE_CLASSES),
    viewport: z.enum(VIEWPORT_BANDS),
    props: eventProps.default({}),
  })
  .superRefine((event, ctx) => {
    for (const message of validateEventProps(event.name, event.props))
      ctx.addIssue({ code: "custom", path: ["props"], message });
  });
export type CreateEventInput = z.infer<typeof createEventSchema>;

export const createEventBatchSchema = z.strictObject({
  events: z.array(createEventSchema).min(1).max(MAX_EVENTS_PER_BATCH),
});

/**
 * The v1 body (one event, free-form props, raw `page`) still sent by a tab that loaded the
 * site before the v2 deploy. It is normalised into the v2 shape, then validated strictly.
 */
const legacyEventSchema = contextSchema.extend({
  name: z.string().max(50),
  visitor_id: visitorIdSchema,
  page: z.string().max(200).default("/"),
  props: eventProps.default({}),
});

export type ParsedEvent = Omit<CreateEventInput, "event_id"> & {
  /** Absent for v1 events; the API then assigns its own id. */
  event_id?: string;
};

/**
 * Accept `{ events: [...] }`, a single v2 event, or a single v1 event, and return v2 events
 * that passed the catalog. Nothing about a rejected body is reported back.
 */
export function parseEventPayload(
  value: unknown,
): { ok: true; events: ParsedEvent[] } | { ok: false } {
  if (value && typeof value === "object" && "events" in value) {
    const batch = createEventBatchSchema.safeParse(value);
    if (!batch.success) return { ok: false };
    const first = batch.data.events[0]!;
    const consistent = batch.data.events.every((e) =>
      [
        "visitor_id",
        "view_id",
        "owner",
        "experiment_id",
        "source",
        "acquisition_channel",
        "route",
      ].every((key) => e[key as keyof typeof e] === first[key as keyof typeof first]),
    );
    return consistent ? { ok: true, events: batch.data.events } : { ok: false };
  }
  if (value && typeof value === "object" && "v" in value) {
    const single = createEventSchema.safeParse(value);
    return single.success ? { ok: true, events: [single.data] } : { ok: false };
  }
  const legacy = legacyEventSchema.safeParse(value);
  if (!legacy.success || !EXPERIMENTS.some((e) => e.id === legacy.data.experiment_id))
    return { ok: false };
  const normalized = normalizeEvent(legacy.data.name, legacy.data.props);
  if (!normalized || validateEventProps(normalized.name, normalized.props).length)
    return { ok: false };
  return {
    ok: true,
    events: [
      {
        v: ANALYTICS_SCHEMA_VERSION,
        view_id: "legacy-v1",
        name: normalized.name,
        experiment_id: legacy.data.experiment_id,
        source: legacy.data.source,
        acquisition_channel: legacy.data.acquisition_channel,
        visitor_id: legacy.data.visitor_id,
        route: routeId(legacy.data.page),
        device: "unknown",
        viewport: "unknown",
        props: normalized.props,
      },
    ],
  };
}

/** Body of `POST /api/events/forget`: the visitor id this browser holds. */
/**
 * Body of `POST /api/events/forget`: the visitor id and the browser's deletion key. Only events
 * whose `owner` is the key's hash are erased, so knowing a visitor id alone deletes nothing.
 */
export const forgetVisitorSchema = z.strictObject({
  visitor_id: visitorIdSchema,
  key: z.string().regex(DELETION_KEY_PATTERN),
});
